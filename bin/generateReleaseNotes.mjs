// Generates the release notes the Welcome panel shows, from CHANGELOG.md.
//
//   CHANGELOG.md  ->  webview-ui/src/generated/releaseNotes.ts
//
// Generating the list is what stops the upgrade screen from telling a user
// about a release older than the one they just installed. Run via
// `pnpm run generate:release-notes`, which `webview:build` chains; the output is
// committed, and `--check` fails when it has drifted from CHANGELOG.md.
import { execFileSync } from "node:child_process"
import fs from "node:fs"
import { createRequire } from "node:module"
import path from "node:path"

const require = createRequire(import.meta.url)

// How many changelog sections the panel shows. The rest are a click away on the
// linked full changelog.
const SECTION_COUNT = 6

const repoRoot = path.resolve(import.meta.dirname, "..")
const changelogPath = path.join(repoRoot, "CHANGELOG.md")
const outPath = path.join(repoRoot, "webview-ui", "src", "generated", "releaseNotes.ts")

// `## [3.5.4] - 2026-09-15`, or `## [Unreleased]` with no date.
const sectionHeading = /^## \[([^\]]+)\](?:\s+-\s+(\S+))?\s*$/

function parseChangelog(markdown) {
  const releases = []
  let current
  for (const line of markdown.split("\n")) {
    const heading = sectionHeading.exec(line)
    if (heading) {
      if (releases.length === SECTION_COUNT) {
        break
      }
      current = { version: heading[1], date: heading[2] ?? null, entries: [] }
      releases.push(current)
      continue
    }
    if (current && line.startsWith("- ")) {
      current.entries.push(line.slice(2).trim())
    }
  }
  const empty = releases.filter((release) => release.entries.length === 0)
  if (empty.length > 0) {
    throw new Error(
      `No entries parsed for ${empty.map((release) => release.version).join(", ")} in CHANGELOG.md`,
    )
  }
  return releases
}

function render(releases) {
  return [
    `// Generated by bin/${path.basename(import.meta.filename)} from CHANGELOG.md. Do not edit.`,
    "",
    "export interface ReleaseNote {",
    "  version: string",
    "  /** ISO date, or null for a section that has not been released yet. */",
    "  date: string | null",
    "  entries: string[]",
    "}",
    "",
    `export const releaseNotes: ReleaseNote[] = ${JSON.stringify(releases, undefined, 2)}`,
    "",
  ].join("\n")
}

// Formatted through oxfmt so the committed file passes `format:check` whatever
// the changelog's wording does to line lengths.
//
// oxfmt is spawned directly rather than through `pnpm exec`: pnpm writes its own
// notices (engine mismatch, update notifier) to stdout, and this stdout becomes
// the generated file.
function format(source) {
  const oxfmtManifest = require.resolve("oxfmt/package.json")
  const oxfmtBin = path.resolve(
    path.dirname(oxfmtManifest),
    JSON.parse(fs.readFileSync(oxfmtManifest, "utf8")).bin.oxfmt,
  )
  return execFileSync(process.execPath, [oxfmtBin, `--stdin-filepath=${outPath}`], {
    cwd: repoRoot,
    input: source,
    encoding: "utf8",
  })
}

const generated = format(render(parseChangelog(fs.readFileSync(changelogPath, "utf8"))))

if (process.argv.includes("--check")) {
  const committed = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : ""
  if (committed !== generated) {
    console.error(
      `DRIFT: ${path.relative(repoRoot, outPath)} does not match CHANGELOG.md.\n` +
        "Run 'pnpm run generate:release-notes' and commit the result.",
    )
    process.exit(1)
  }
  console.log(`OK: ${path.relative(repoRoot, outPath)} matches CHANGELOG.md`)
} else {
  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, generated)
  console.log(`Wrote ${SECTION_COUNT} release notes into ${path.relative(repoRoot, outPath)}`)
}
